/**
 * ============================================================================
 * 新手导读：这份文件在干什么？
 * ============================================================================
 *
 * 目标：用最简例子搞懂 LangGraph「图」怎么跑——状态怎么传、节点怎么串、
 * 最后怎么 invoke 一次看结果。
 *
 * 核心类比：
 * - State（状态）= 一张会在各站之间传递的「接力棒 / 草稿纸」
 * - Node（节点）= 流水线上的加工站，读草稿纸、改一改、交出去
 * - Edge（边）  = 站与站之间的箭头：做完 A 去 B
 * - START / END = 入口大门 / 出口大门（框架自带，不用自己实现）
 * - compile     = 把「设计图」焊成可运行的机器
 * - invoke      = 塞进初始数据，按箭头跑完一整趟
 *
 * 为什么先学这个？
 * - Agent、工具调用、分支条件，底层都是「带状态的图」
 * - 先看清「状态 + 节点 + 边」，再叠记忆/工具才不会晕
 *
 * ----------------------------------------------------------------------------
 * 主流程怎么走？（对应下面从定义到 invoke）
 * ----------------------------------------------------------------------------
 *  1. 用 Annotation 定义状态长什么样（这里只有一个字段 text）
 *  2. 写两个节点函数 step1 / step2（各自在 text 后面追加一段字）
 *  3. 用 StateGraph 登记节点，再画边：START → step1 → step2 → END
 *  4. compile 得到可执行图
 *  5.（可选）导出 Mermaid，方便画出来看结构
 *  6. invoke({ text: "hello" }) 跑一遍，打印最终状态
 *
 * 阅读建议：先扫一遍「状态定义 → 节点 → 画边 → invoke」，再对照控制台输出。
 * ============================================================================
 */

import { Annotation, END, START, StateGraph } from "@langchain/langgraph";

// ============================================================================
// 1. 定义状态：整张图共享的「草稿纸」长什么样
// ============================================================================

/**
 * StateAnnotation：用 Annotation.Root 声明图的状态 schema。
 *
 * 这里只有一个通道（channel）叫 text：
 * - reducer：新旧值怎么合并。`(_prev, _next) => _next` 表示「后来的直接覆盖前面的」
 * - default：一开始没人塞值时，用空字符串当默认
 *
 * 新手易混点：
 * - 节点 return 的不是「整个世界」，而是「要更新的字段」；框架会按 reducer 合进总状态
 * - 若 reducer 写成「拼接 / 累加」，多次更新会叠在一起；这里选覆盖，最直观
 */
const StateAnnotation = Annotation.Root({
    text: Annotation({
        reducer: (_prev, _next) => _next,
        default: () => ''
    })
})

// ============================================================================
// 2. 定义节点：每个函数吃「当前状态」，吐「要改的字段」
// ============================================================================

/**
 * step1：第一站加工。
 * 读出 state.text，在后面拼上 " -> step1"，再作为新的 text 交回去。
 * 例：入参 { text: "hello" } → 返回 { text: "hello -> step1" }
 */
const step1 = (state) => ({ text: `${state.text} -> step1` });

/**
 * step2：第二站加工，写法同 step1，只是标记改成 " -> step2"。
 * 因为边规定 step1 做完才到这里，所以此时 text 里通常已经带有 step1 的痕迹。
 */
const step2 = (state) => ({ text: `${state.text} -> step2` });

// ============================================================================
// 3. 装配图：登记节点 + 画边，然后 compile
// ============================================================================

/**
 * 装配顺序（对应导读 3～4）：
 * 1. new StateGraph(StateAnnotation) —— 这张图用上面的状态 schema
 * 2. addNode —— 给节点起名并挂上函数（名字会出现在边和 Mermaid 里）
 * 3. addEdge —— 规定执行顺序：START → step1 → step2 → END
 * 4. compile —— 生成可 invoke 的 CompiledGraph
 *
 * 类比：先画地铁线路图，再通车；没 compile 前只是设计稿。
 */
const graph = new StateGraph(StateAnnotation)
    .addNode("step1", step1)
    .addNode("step2", step2)
    .addEdge(START, "step1")
    .addEdge("step1", "step2")
    .addEdge("step2", END)
    .compile();

// ============================================================================
// 4. 可视化：把图结构导出成 Mermaid（不改变运行逻辑）
// ============================================================================

// 导出为 Mermaid：可复制到 https://mermaid.live 或 Markdown 的 ```mermaid 代码块
const drawable = await graph.getGraphAsync();
const mermaid = drawable.drawMermaid({ withStyles: true });
console.log(mermaid);

// ============================================================================
// 5. 执行：塞入初始状态，沿边跑完，拿到最终 state
// ============================================================================

/**
 * invoke：同步跑完整条路径（本例无分支、无循环）。
 *
 * 输入 { text: "hello" } 之后，草稿纸大致会变成：
 *   "hello" → "hello -> step1" → "hello -> step1 -> step2"
 *
 * 打印的 result 就是最终状态对象，例如 { text: "hello -> step1 -> step2" }。
 */
const result = await graph.invoke({ text: "hello" });
console.log("result:", result);

